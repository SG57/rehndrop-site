"""Copy full lyrics for the slugs Cord has cleared (curation.json "lyrics") into src/data/lyrics.json.

Reads the READ-ONLY track catalog at D:/rehndrop/tracks (never writes there). For each cleared slug:

- text: the track's one canonical lyric file, text/lyrics.txt, verbatim. Lines that are only a
  bracketed tag ("[Verse 1]", "[soft piano]") are arrangement tags, not sung words, and are left
  out; runs of blank lines collapse to one stanza break. Nothing else is altered.
- timed: when text/lyrics.aligned.json exists, the word start times from its latest run
  ([seconds, word] pairs only, no other fields), for highlighting inside the preview window.

Numbered drafts (lyrics-1.txt, lyrics-2a.txt), style files and every other file are never read.
A cleared slug without text/lyrics.txt is skipped with a warning; text is never rebuilt from timings.

    python scripts/export_lyrics.py            # writes src/data/lyrics.json
    python scripts/export_lyrics.py --check    # exits 1 if the file on disk is stale
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TRACKS_DIR = Path("D:/rehndrop/tracks")
CURATION = ROOT / "src" / "data" / "curation.json"
OUT = ROOT / "src" / "data" / "lyrics.json"

TAG_LINE = re.compile(r"^\s*\[[^\]]*\]\s*$")


def clean_text(raw: str) -> str:
    lines = [ln.rstrip() for ln in raw.replace("\r\n", "\n").replace("\r", "\n").split("\n")]
    kept = [ln for ln in lines if not TAG_LINE.match(ln)]
    out: list[str] = []
    for ln in kept:
        if ln.strip() == "":
            if out and out[-1] != "":
                out.append("")
        else:
            out.append(ln)
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out)


def timed_words(path: Path):
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        print(f"  warn: {path} unreadable ({e}); no timings", file=sys.stderr)
        return None
    runs = data.get("runs") or []
    if not runs:
        return None
    words = runs[-1].get("words") or []
    pairs = [[round(float(w["start"]), 3), str(w["w"])] for w in words if "start" in w and "w" in w]
    return pairs or None


def build() -> dict:
    curation = json.loads(CURATION.read_text(encoding="utf-8"))
    cleared = curation.get("lyrics") or []
    tracks = {}
    for slug in cleared:
        text_dir = TRACKS_DIR / slug / "text"
        src = text_dir / "lyrics.txt"
        if not src.is_file():
            print(f"  skip {slug}: no {src}", file=sys.stderr)
            continue
        text = clean_text(src.read_text(encoding="utf-8"))
        if not text:
            print(f"  skip {slug}: {src} has no sung lines", file=sys.stderr)
            continue
        entry = {"text": text, "timed": None}
        aligned = text_dir / "lyrics.aligned.json"
        if aligned.is_file():
            entry["timed"] = timed_words(aligned)
        tracks[slug] = entry
        print(f"  {slug}: {text.count(chr(10)) + 1} lines{' + timings' if entry['timed'] else ''}")
    return {
        "_note": "Generated by scripts/export_lyrics.py for the slugs in curation.json lyrics. Do not edit.",
        "tracks": tracks,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if src/data/lyrics.json is stale")
    args = ap.parse_args(argv)
    body = json.dumps(build(), ensure_ascii=False, indent=2) + "\n"
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != body:
            print("lyrics.json is stale: run python scripts/export_lyrics.py", file=sys.stderr)
            return 1
        print("lyrics.json is current")
        return 0
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(json.loads(body)['tracks'])} tracks)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
