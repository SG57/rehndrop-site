#!/usr/bin/env python
"""Export posted Instagram reels for the site's reel posters (each links out to its post).

    python scripts/export_reels.py            # idempotent; --force re-writes the posters

Source of truth: D:/rehndrop/tracks/ig-ledger.json "posted" (maintained by ig_stage.py), read
only. For each post it writes the published cover as the poster to src/assets/reels/<item>.jpg
and the entry to src/data/reels.json. The site hosts no video: every poster links to Instagram,
and any web cut left in public/reels/ from an earlier export is removed.
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

from PIL import Image

TRACKS = Path("D:/rehndrop/tracks")
SITE = Path(__file__).resolve().parent.parent
OUT_VIDEO = SITE / "public" / "reels"
OUT_POSTER = SITE / "src" / "assets" / "reels"
OUT_DATA = SITE / "src" / "data" / "reels.json"
CATALOG = SITE / "src" / "data" / "catalog.json"


def norm(s: str) -> str:
    s = s.lower().replace("’", "'").replace("‘", "'")
    return re.sub(r"\s+", " ", re.sub(r"[^a-z0-9 ]", "", s)).strip()


def published_cover(social: Path, item: str) -> Path | None:
    """`ig_stage.py settle` files the published cover as <item>-cover.jpg, but skips that copy when
    the track already holds the same bytes, which it does when the staged draft went out unchanged
    (005). Then the draft is the cover, provided it still matches what the stage record shipped."""
    settled = social / f"{item}-cover.jpg"
    if settled.is_file():
        return settled
    draft, record = social / "stage" / "drafts" / item / "cover.jpg", social / "stage" / f"{item}.json"
    if draft.is_file() and record.is_file():
        shipped = json.loads(record.read_text(encoding="utf-8")).get("files", {}).get("cover.jpg")
        if shipped == hashlib.sha256(draft.read_bytes()).hexdigest():
            return draft
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    ledger = json.loads((TRACKS / "ig-ledger.json").read_text(encoding="utf-8"))
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))["tracks"]
    by_title = {norm(t["title"]): t["slug"] for t in catalog}
    posts = sorted(ledger.get("posted", {}).items(), key=lambda kv: kv[1].get("posted_at") or "", reverse=True)

    OUT_POSTER.mkdir(parents=True, exist_ok=True)
    reels, problems = [], []
    for item, p in posts:
        slug = by_title.get(norm(p.get("track", "")))
        url = re.sub(r"\?.*$", "", p.get("post_url") or "")
        if not slug or not url:
            problems.append(f"{item}: track '{p.get('track')}' not in the catalog or no post_url; skipped")
            continue
        entry = {"id": item, "track": slug, "title": p["track"], "url": url,
                 "postedAt": (p.get("posted_at") or "")[:10], "angle": p.get("angle"), "poster": None}
        track_dir = TRACKS / slug
        cover = published_cover(track_dir / "video" / "social", item)
        if cover:
            poster = OUT_POSTER / f"{item}.jpg"
            if args.force or not poster.exists() or poster.stat().st_mtime < cover.stat().st_mtime:
                Image.open(cover).convert("RGB").resize((720, 1280), Image.LANCZOS).save(poster, quality=84, progressive=True, optimize=True, comment=b"")  # no encoder comment carried over from the cover
            entry["poster"] = f"reels/{item}.jpg"
        print(f"{item:<34} {slug:<18} poster {'yes' if entry['poster'] else 'MISSING'}, links out")
        reels.append(entry)

    if OUT_VIDEO.is_dir():
        for stale in OUT_VIDEO.glob("*.mp4"):
            stale.unlink()

    OUT_DATA.write_text(json.dumps({"_note": "Generated by scripts/export_reels.py from ig-ledger.json. Do not edit.", "reels": reels},
                                   indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for pr in problems:
        print("  !", pr)
    print(f"{len(reels)} reels written to {OUT_DATA.relative_to(SITE)}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
